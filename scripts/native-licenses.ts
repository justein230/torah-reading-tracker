// Turns the license lists that the native build tools produce into the markdown files in licenses/native/:
//   android: the JSON that the AboutLibraries Gradle plugin exports (`./gradlew :app:exportLibraryDefinitions`)
//   ios:     the acknowledgements file that CocoaPods writes during `pod install`
// Run through `npm run licenses:android` / `npm run licenses:ios` (see docs/LICENSES.md).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { detectLicenseIds } from './license-expression.mjs';

/** One license a native library ships under, with its text. */
interface LibraryLicense {
  name: string;
  text: string;
}

/** One native library together with the license texts it ships under (more than one when it is multi-licensed). */
interface Library {
  name: string;
  /** Who holds the copyright, when the source says so. */
  credit?: string;
  licenses: LibraryLicense[];
}

// AboutLibraries exports each library's licenses as keys into a top-level `licenses` map; accept inline objects too.
interface AboutLibrariesLicense { name?: string; spdxId?: string; content?: string; licenseContent?: string }
export interface AboutLibrariesExport {
  libraries: {
    uniqueId: string;
    artifactVersion?: string;
    name?: string;
    developers?: { name?: string }[];
    organization?: { name?: string };
    licenses?: (string | AboutLibrariesLicense)[];
  }[];
  licenses?: Record<string, AboutLibrariesLicense>;
}

/** A code fence long enough that license text containing backticks cannot end it early. */
function fenced(text: string): string {
  const longestRun = Math.max(2, ...(text.match(/`+/g) ?? []).map(run => run.length));
  const fence = '`'.repeat(longestRun + 1);
  return `${fence}text\n${text}\n${fence}`;
}

/**
 * Libraries sharing the same license text are listed together, so e.g. Apache-2.0 appears once rather
 * than once per AndroidX artifact. Sections are ordered by number of libraries, then name, so regenerating
 * gives a stable file and small diffs.
 */
function groupByLicense(libraries: Library[]): string {
  const groups = new Map<string, Library[]>();
  for (const library of libraries) {
    const key = library.licenses.map(({ text }) => text.replace(/\s+/g, ' ').trim()).join('\n');
    groups.set(key, [...(groups.get(key) ?? []), library]);
  }
  const heading = (library: Library) => library.licenses.map(({ name }) => name).join(' + ');
  // A fixed locale, so the file does not depend on the machine that generates it (CI compares it with the committed one).
  const byText = (a: string, b: string) => a.localeCompare(b, 'en');
  return [...groups.values()]
    .sort((a, b) => b.length - a.length || byText(heading(a[0]!), heading(b[0]!)))
    .map(group => {
      const sorted = [...group].sort((a, b) => byText(a.name, b.name));
      const credits = [...new Set(sorted.flatMap(({ credit }) => credit ? [credit] : []))].sort(byText);
      const covered = sorted.map(({ name }) => '`' + name + '`').join(', ');
      const { licenses } = group[0]!;
      return [
        `## ${heading(group[0]!)}`,
        `Covers: ${covered}`,
        ...(credits.length ? [credits.map(credit => `- ${credit}`).join('\n')] : []),
        // A multi-licensed library shows each text under its license's name.
        ...licenses.map(({ name, text }) => (licenses.length > 1 ? `${name}:\n\n` : '') + fenced(text.trim())),
      ].join('\n\n');
    })
    .join('\n\n');
}

function withHeader(title: string, npmScript: string, body: string): string {
  return `# ${title}\n\nGenerated by \`npm run ${npmScript}\`. Do not edit by hand.\n\n${body}\n`;
}

const LICENSE_NAMES: Record<string, string> = {
  'Apache-2.0': 'Apache License 2.0',
  MIT: 'MIT License',
  BSD: 'BSD license',
  ISC: 'ISC license',
  Zlib: 'zlib license',
  'CC0-1.0': 'CC0 1.0 Universal',
  WTFPL: 'WTFPL',
  GPL: 'GNU General Public License',
};

/** Recognise the common licenses by their standard wording; the tools' own license names are often missing or vague. */
export function detectLicenseName(text: string): string | undefined {
  const id = detectLicenseIds(text).find(found => ['Apache-2.0', 'MIT', 'BSD'].includes(found));
  return id && LICENSE_NAMES[id];
}

/**
 * Writes the document, but refuses to when a library has no license text: an attribution file with gaps
 * must not be committed unnoticed (the npm build fails the same way).
 */
function render(title: string, npmScript: string, libraries: Library[]): string {
  // A multi-licensed library must ship every one of its licenses (Maven does not say AND or OR), so name the ones lacking text.
  const missing = libraries.flatMap(({ name, licenses }) => {
    const empty = licenses.filter(({ text }) => !text.trim());
    if (empty.length === 0) return [];
    return [licenses.length > 1 ? `${name} (${empty.map(license => license.name).join(', ')})` : name];
  });
  if (missing.length > 0) {
    throw new Error(`No license text for: ${missing.join(', ')}\n` +
      'Add licenses/native/overrides/<name>.txt for each (see docs/LICENSES.md).');
  }
  return withHeader(title, npmScript, groupByLicense(libraries));
}

/**
 * Texts for libraries whose build metadata carries none, keyed by library id (`group:artifact`) or by license id
 * (e.g. `Apache-2.0`). Loaded from licenses/native/overrides/, where `__` in a file name stands for `:`.
 */
export type TextOverrides = Record<string, string>;

/** Android libraries from an AboutLibraries export, as the content of licenses/native/android.md. */
export function formatAndroidLicenses(exported: AboutLibrariesExport, overrides: TextOverrides = {}): string {
  const libraries = exported.libraries.map((library): Library => {
    // A library without any license entry still gets one (empty) so that render() reports it.
    const licenseKeys = library.licenses?.length ? library.licenses : [undefined];
    const licenses = licenseKeys.map((licenseKey): LibraryLicense => {
      const license = typeof licenseKey === 'string' ? exported.licenses?.[licenseKey] : licenseKey;
      // A text keyed by library id cannot tell its licenses apart, so only a single-license library may use one.
      const libraryOverride = licenseKeys.length === 1 ? overrides[library.uniqueId] : undefined;
      const text = (license?.content ?? license?.licenseContent
        ?? libraryOverride
        ?? overrides[license?.spdxId ?? ''] ?? overrides[typeof licenseKey === 'string' ? licenseKey : ''] ?? '').trim();
      return { text, name: detectLicenseName(text) || license?.name || license?.spdxId || library.name || library.uniqueId };
    });
    const credit = library.organization?.name
      ?? library.developers?.map(({ name }) => name).filter(Boolean).join(', ');
    return {
      name: library.artifactVersion ? `${library.uniqueId}:${library.artifactVersion}` : library.uniqueId,
      ...(credit ? { credit: `${library.name ?? library.uniqueId}: ${credit}` } : {}),
      licenses,
    };
  });
  return render('Android libraries', 'licenses:android', libraries);
}

/**
 * iOS pods from the CocoaPods acknowledgements file, as the content of licenses/native/ios.md.
 * The file is a header, then one `## <Pod>` section per pod holding its license text, then a "Generated by" footer.
 */
export function formatIosAcknowledgements(acknowledgements: string): string {
  const libraries = acknowledgements
    .split(/^## /m)
    .slice(1) // the intro before the first pod
    .map((section): Library => {
      const [name = '', ...rest] = section.split('\n');
      const text = rest.join('\n').replace(/^Generated by CocoaPods.*$/m, '').trim();
      // The acknowledgements carry no license ids, so a pod whose text holds several licenses is spotted by its wording.
      const detected = detectLicenseIds(text);
      const licenseName = detected.length > 1
        ? detected.map(id => LICENSE_NAMES[id] ?? id).join(' + ')
        : detectLicenseName(text) ?? name.trim();
      return { name: name.trim(), licenses: [{ name: licenseName, text }] };
    })
    .filter(({ name }) => name && name !== 'Acknowledgements');
  return render('iOS libraries', 'licenses:ios', libraries);
}

const OVERRIDES_DIR = 'licenses/native/overrides';

function readOverrides(): TextOverrides {
  return Object.fromEntries(readdirSync(OVERRIDES_DIR)
    .filter(file => file.endsWith('.txt'))
    .map(file => [file.slice(0, -'.txt'.length).replaceAll('__', ':'), readFileSync(`${OVERRIDES_DIR}/${file}`, 'utf-8')]));
}

const OUTPUTS = {
  android: { file: 'licenses/native/android.md', format: (input: string) => formatAndroidLicenses(JSON.parse(input), readOverrides()) },
  ios:     { file: 'licenses/native/ios.md',     format: formatIosAcknowledgements },
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const [platform, inputFile] = process.argv.slice(2);
  const output = OUTPUTS[platform as keyof typeof OUTPUTS];
  if (!output || !inputFile) {
    console.error('Usage: tsx scripts/native-licenses.ts <android|ios> <input file>');
    process.exit(1);
  }
  try {
    writeFileSync(output.file, output.format(readFileSync(inputFile, 'utf-8')));
    console.log(`Wrote ${output.file}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
